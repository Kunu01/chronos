import rateLimit from 'express-rate-limit';

export const authRateLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 minutes
  max: 15, // 5 in strict prod; 15 in dev for comfortable testing while enforcing 429
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    error: {
      code: 'TOO_MANY_REQUESTS',
      message: 'Maximum attempts reached. IP locked for 15 minutes.',
      details: null,
    },
  },
});

